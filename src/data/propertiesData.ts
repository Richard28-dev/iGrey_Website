export type PropertyStatus = 'available' | 'under-offer' | 'upcoming' | 'sold';
export type ListingType = 'sale' | 'rent' | 'lease';
export type PropertyType = 'residential' | 'commercial' | 'land' | 'office' | 'shop' | 'warehouse';

export interface PropertyListing {
  id: string; // e.g. "IGH-RES-01"
  status: PropertyStatus; // 'available' | 'under-offer' | 'upcoming' | 'sold'
  listingType: ListingType; // 'sale' | 'rent' | 'lease'
  propertyType: PropertyType; // 'residential' | 'commercial' | 'land' | 'office' | 'shop' | 'warehouse'
  category: string; // e.g. "Executive Villa", "Gated Apartment"
  bhk?: number; // 1, 2, 3, 4, 5
  title: string;
  city: string; // "Bangalore" | "Mysuru" | "Hyderabad" | "Chennai"
  location: string;
  price: string; // Display string, e.g. "₹8.75 Cr", "₹1,25,000"
  priceNumber: number; // Rupees (monthly for rent/lease, total for sale)
  priceSuffix?: string; // "/mo"
  note?: string; // e.g. "Deposit: ₹6.0 L", "Lease: ₹12.0 L (2-3 Yrs)"
  features: string[]; // ['Fully Furnished', 'Gated Society', 'Swimming Pool', 'Covered Parking', 'Clubhouse', 'Rooftop Deck']
  details: string; // Summary line: "4,800 sq ft • Private Courtyard & Plunge Pool • 3 Covered Car Parks"
  images: string[];
  featured: boolean;
  createdAt: string; // ISO date string for sorting
  description?: string;
  verified?: boolean; // verified listings flag
  // Optional extended specs for modal dialog
  sqft?: string;
  tenure?: string;
  maintenance?: string;
  availability?: string;
}

